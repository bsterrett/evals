def sentences(message: str) -> set[str]:
    return {part.strip().rstrip('.') for part in message.split('. ')}


def main() -> None:
    data = Path(REPO + "experiments/recurrent_steganography/data")
    earlier = {case["message"] for name in ("covers-v1.json", "reference-covers-v1.json", "confirmation-covers-v1.json")
        for case in json.loads((data / name).read_text(encoding="utf-8"))}
    earlier_sentences = set().union(*(sentences(message) for message in earlier))
    cases, dev, cal, chk = [], 0, 0, 0
    for family, messages in FAMILIES.items():
        assert len(messages) == 40, (family, len(messages))
        for index, message in enumerate(messages):
            problems = content_problems(message)
            assert not problems, (family, message, problems)
            assert message not in earlier, message
            assert not sentences(message) & earlier_sentences, message
            if index < 36:
                dev += 1
                cases.append(dict(id=f"both-dev-{dev:03d}", split="development", family=family, message=message))
            elif index < 39:
                cal += 1
                cases.append(dict(id=f"both-cal-{cal:02d}", split="judge_calibration", family=family, message=message))
            else:
                chk += 1
                cases.append(dict(id=f"both-chk-{chk}", split="encoder_check", family=family, message=message))
    messages = [case["message"] for case in cases]
    assert len(set(messages)) == len(messages) == 320
    text = "[\n" + ",\n".join("  " + json.dumps(c, ensure_ascii=False, separators=(",", ":")) for c in cases) + "\n]\n"
    (data / "both-reasoning-covers-v1.json").write_text(text, encoding="utf-8", newline="\n")
    words = [len(message.split()) for message in messages]
    print(len(cases), dev, cal, chk, sum(words) / len(words))


if __name__ == "__main__":
    main()
